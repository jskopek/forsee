import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodeBase64, type ModelStats } from '@forsee/prediction';
import { buildFromFiles, readWordList } from './files';

/**
 * The seed model: built from the original, MIT-licensed text in
 * `packages/prediction/data/seed/` and written both as `seed-model.bin` and
 * as a base64 module that `loadSeedModel()` imports.
 */

/** Repository root (this file is `tools/lm-build/{src,dist}/…`). */
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const SEED_DIR = join(REPO_ROOT, 'packages/prediction/data/seed');
export const SEED_MODEL_PATH = join(SEED_DIR, 'seed-model.bin');
export const SEED_MODULE_PATH = join(
  REPO_ROOT,
  'packages/prediction/src/seed/seed-model.generated.ts',
);

export const SEED_BUILD_OPTIONS = {
  locale: 'en',
  order: 3,
  minNgramCount: 1,
  wordListWeight: 0.3,
  description: 'Forsee seed model: original MIT-licensed text, for development only',
} as const;

/** Builds the seed model in memory. */
export async function buildSeedModel(): Promise<{ bytes: Uint8Array; stats: ModelStats }> {
  const wordList = await readWordList(join(SEED_DIR, 'vocabulary.txt'));
  return buildFromFiles([join(SEED_DIR, 'corpus.txt')], { ...SEED_BUILD_OPTIONS, wordList });
}

/** The TypeScript module embedding `bytes` (formatted the way Prettier would). */
export function renderSeedModule(bytes: Uint8Array): string {
  return [
    '// Generated by tools/lm-build (`pnpm --filter @forsee/lm-build seed`). Do not edit.',
    '// Built from packages/prediction/data/seed (original text written for Forsee, MIT).',
    'export const SEED_MODEL_BASE64 =',
    `  '${encodeBase64(bytes)}';`,
    '',
  ].join('\n');
}

/** Reads the checked-in seed sources and the generated module text. */
export async function readCheckedInSeed(): Promise<{ bin: Uint8Array; module: string }> {
  return {
    bin: new Uint8Array(await readFile(SEED_MODEL_PATH)),
    module: await readFile(SEED_MODULE_PATH, 'utf8'),
  };
}

/** Rebuilds and writes `seed-model.bin` and the generated module. */
export async function writeSeedModel(): Promise<ModelStats> {
  const { bytes, stats } = await buildSeedModel();
  await writeFile(SEED_MODEL_PATH, bytes);
  await writeFile(SEED_MODULE_PATH, renderSeedModule(bytes));
  return stats;
}
